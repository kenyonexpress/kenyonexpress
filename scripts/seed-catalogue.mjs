#!/usr/bin/env node
/**
 * Seeds a full-looking catalogue: 14 complete suppliers and 40 Hebrew deals.
 *
 * WHY THIS EMITS SQL RATHER THAN CALLING SUPABASE
 *
 * The `SUPABASE_SECRET_KEY` in `.env.local` is not this project's — it is the
 * stock local-development demo key, and the hosted project answers "Invalid API
 * key" to every request made with it. `seed-test-data.mjs` next door assumes a
 * working key and cannot run here for that reason. The path that DOES work is
 * MCP, which speaks SQL, so the primary output of this script is a single
 * idempotent statement block.
 *
 * WHAT IT WILL NOT DO
 *
 * Write anything by itself. Default is a dry run that prints what it would
 * write and touches nothing, the same shape `WP_IMPORT_ALLOW_WRITES` gives the
 * WordPress import: the artifact is reviewable before it exists anywhere. These
 * are 40 demo products destined for a live catalogue that already holds 61 real
 * ones, and that is a decision to take deliberately rather than as a side effect
 * of running a script.
 *
 * TWO THINGS THE SQL HAS TO DO THAT THE APPLICATION DOES FOR ITSELF
 *
 *   1. `approval_status`. The `enforce_product_approval` trigger returns early
 *      when `auth.uid() IS NULL`, which is exactly the case for SQL run through
 *      MCP or the service role. So the admin path that would set `approved` on
 *      an activated product never runs, and a seed that omitted the column would
 *      leave 40 products `active` and unapproved — a state the admin screens
 *      would then treat as pending.
 *   2. `category_id`. Resolved by SLUG against the categories that already
 *      exist, never invented: a seed that created its own categories would put
 *      demo entries in the site navigation.
 *
 * Usage (from the repo root):
 *   node scripts/seed-catalogue.mjs            # dry run: summary, writes nothing
 *   node scripts/seed-catalogue.mjs --sql      # the idempotent upsert block
 *   node scripts/seed-catalogue.mjs --clean-sql # remove exactly what it created
 */

import { PRODUCTS, SUPPLIERS, seededIds } from './seed/catalogue-data.mjs'
import { DEMO_PRODUCTS, DEMO_SUPPLIERS, demoIds } from './seed/demo-data.mjs'

const args = new Set(process.argv.slice(2))

/**
 * Two datasets, one emitter (marathon step 16). The default is the curated
 * catalogue seed; --demo swaps in the demo-production profile (3 suppliers,
 * 40 physical, 20 coupons) on its own d3e3… id namespace, so the two seeds
 * coexist, count apart and clean apart. Same rules either way: SQL out,
 * nothing executed, review before MCP.
 */
const CATALOGUE_SET = {
  label: 'scripts/seed-catalogue.mjs',
  suppliers: SUPPLIERS,
  products: PRODUCTS,
  ids: seededIds,
}
const DEMO_SET = {
  label: 'scripts/seed-catalogue.mjs --demo',
  suppliers: DEMO_SUPPLIERS,
  products: DEMO_PRODUCTS,
  ids: demoIds,
}

/** Single quotes doubled. Every value here is ours, but a seed is still SQL. */
function q(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'number') return String(value)
  return `'${String(value).replace(/'/g, "''")}'`
}

function supplierRows(set = CATALOGUE_SET) {
  return set.suppliers
    .map(
      (s) =>
        `  (${q(s.id)}, ${q(s.name)}, ${q(s.contactName)}, ${q(s.contactEmail)}, ${q(s.contactPhone)}, ` +
        `${q(s.whatsapp)}, ${q(s.address)}, ${q(s.city)}, ${q(s.website)}, ${q(s.businessId)}, ` +
        `${q(s.logoUrl)}, ${s.defaultSplitPercent})`,
    )
    .join(',\n')
}

function productRows(set = CATALOGUE_SET) {
  return set.products
    .map(
      (p) =>
        `  (${q(p.id)}, ${q(p.slug)}, ${q(p.nameHe)}, ${q(p.categorySlug)}, ${q(p.supplierId)}, ` +
        `${q(p.type)}, ${p.priceIls}, ${q(p.couponPriceIls)}, ${p.platformPercent}, ` +
        `${q(p.imageUrl)}, ${q(p.shortDescriptionHe)}, ${q(p.seoDescription)}, ` +
        `${q(p.stockQuantity)}, ${q(p.couponExpiryDays)})`,
    )
    .join(',\n')
}

function upsertSql(set = CATALOGUE_SET) {
  return `-- Seed catalogue: ${set.suppliers.length} suppliers, ${set.products.length} products.
-- Idempotent: every statement is an upsert on a fixed id in the 5eed… namespace.
-- Generated by ${set.label}. Do not edit by hand.

INSERT INTO public.suppliers
  (id, name, contact_name, contact_email, contact_phone, whatsapp,
   address, city, website, business_id, logo_url, default_split_percent, status)
-- Every column is cast explicitly. A VALUES list is untyped text, and the
-- first probe of this statement against production answered
--   42804: column "id" is of type uuid but expression is of type text
-- on the very first column.
SELECT v.id::uuid, v.name, v.contact_name, v.contact_email, v.contact_phone, v.whatsapp,
       v.address, v.city, v.website, v.business_id, v.logo_url, v.split::numeric, 'active'
FROM (VALUES
${supplierRows(set)}
) AS v(id, name, contact_name, contact_email, contact_phone, whatsapp,
       address, city, website, business_id, logo_url, split)
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  contact_name = EXCLUDED.contact_name,
  contact_email = EXCLUDED.contact_email,
  contact_phone = EXCLUDED.contact_phone,
  whatsapp = EXCLUDED.whatsapp,
  address = EXCLUDED.address,
  city = EXCLUDED.city,
  website = EXCLUDED.website,
  business_id = EXCLUDED.business_id,
  logo_url = EXCLUDED.logo_url,
  default_split_percent = EXCLUDED.default_split_percent,
  status = 'active',
  deleted_at = NULL;

-- category_id is resolved by slug against the categories that already exist.
-- A row whose category slug is missing is SKIPPED rather than inserted with a
-- null category, which the storefront would render outside every archive.
INSERT INTO public.products
  (id, slug, name_he, category_id, supplier_id, type, status, approval_status,
   price_ils, kenyon_price, coupon_price_ils, is_coupon_enabled,
   platform_percent, supplier_split_percent, commission_percent, commission_type,
   images, short_description_he, seo_description, stock_quantity,
   coupon_expiry_days, published_at)
SELECT v.id::uuid, v.slug, v.name_he, c.id, v.supplier_id::uuid,
       v.type::public.product_type, 'active'::public.product_status,
       -- Written explicitly: enforce_product_approval returns early when
       -- auth.uid() is null, so the admin path that would set this never runs.
       'approved'::public.product_approval_status,
       v.price::numeric, v.price::numeric, v.coupon_price::numeric,
       v.coupon_price IS NOT NULL,
       -- The pair sums to 100, which is the shape every settlement row and
       -- CHECK in this schema expects, and the pair production already carries.
       v.platform_percent::numeric, (100 - v.platform_percent)::numeric,
       -- commission_percent is NOT NULL with no default. It is the legacy
       -- column that predates platform_percent; production carries 5 or 10 on
       -- every active row, and the probe that found this answered
       --   23502: null value in column "commission_percent"
       -- on the first insert. 5 matches the majority of the live catalogue.
       5,
       -- Also NOT NULL with no default, and found the same way. It is the
       -- commission MODEL, not a percent: production carries coupon_absolute on
       -- all 15 coupons and physical_percent on all 46 physical rows, which is
       -- the split lib/commerce/commission.ts implements.
       (CASE WHEN v.coupon_price IS NULL THEN 'physical_percent'
             ELSE 'coupon_absolute' END)::public.commission_type,
       jsonb_build_array(v.image), v.short_desc, v.seo_desc, v.stock::integer,
       v.expiry_days::integer, now()
FROM (VALUES
${productRows(set)}
) AS v(id, slug, name_he, category_slug, supplier_id, type, price, coupon_price,
       platform_percent, image, short_desc, seo_desc, stock, expiry_days)
JOIN public.categories c ON c.slug = v.category_slug
ON CONFLICT (id) DO UPDATE SET
  slug = EXCLUDED.slug,
  name_he = EXCLUDED.name_he,
  category_id = EXCLUDED.category_id,
  supplier_id = EXCLUDED.supplier_id,
  type = EXCLUDED.type,
  status = EXCLUDED.status,
  approval_status = EXCLUDED.approval_status,
  price_ils = EXCLUDED.price_ils,
  kenyon_price = EXCLUDED.kenyon_price,
  coupon_price_ils = EXCLUDED.coupon_price_ils,
  is_coupon_enabled = EXCLUDED.is_coupon_enabled,
  platform_percent = EXCLUDED.platform_percent,
  supplier_split_percent = EXCLUDED.supplier_split_percent,
  commission_percent = EXCLUDED.commission_percent,
  commission_type = EXCLUDED.commission_type,
  images = EXCLUDED.images,
  short_description_he = EXCLUDED.short_description_he,
  seo_description = EXCLUDED.seo_description,
  stock_quantity = EXCLUDED.stock_quantity,
  coupon_expiry_days = EXCLUDED.coupon_expiry_days,
  deleted_at = NULL;
`
}

function cleanSql(set = CATALOGUE_SET) {
  const { suppliers, products } = set.ids()
  return `-- Removes exactly the rows ${set.label} created, by id.
-- Products first: suppliers are referenced with ON DELETE RESTRICT.
DELETE FROM public.products  WHERE id IN (${products.map(q).join(', ')});
DELETE FROM public.suppliers WHERE id IN (${suppliers.map(q).join(', ')});
`
}

function summary(set = CATALOGUE_SET) {
  const coupons = set.products.filter((p) => p.type === 'coupon')
  const percents = new Set(set.products.map((p) => p.platformPercent))
  const categories = new Set(set.products.map((p) => p.categorySlug))
  return [
    'DRY RUN. Nothing was written.',
    '',
    `suppliers            ${set.suppliers.length}  (all with address, city, phone and logo)`,
    `products             ${set.products.length}`,
    `  coupons            ${coupons.length}`,
    `  physical           ${set.products.length - coupons.length}`,
    `distinct platform_%  ${percents.size}`,
    `categories used      ${[...categories].join(', ')}`,
    '',
    'To apply, review the statements and run them through MCP:',
    '  node scripts/seed-catalogue.mjs --sql',
    'To remove them again:',
    '  node scripts/seed-catalogue.mjs --clean-sql',
  ].join('\n')
}

export { upsertSql, cleanSql, summary, DEMO_SET, CATALOGUE_SET }

// Only when run as a command. Without the guard, importing this module from a
// test writes 19KB of SQL to the runner's stdout.
if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const set = args.has('--demo') ? DEMO_SET : CATALOGUE_SET
  if (args.has('--sql')) process.stdout.write(upsertSql(set))
  else if (args.has('--clean-sql')) process.stdout.write(cleanSql(set))
  else process.stdout.write(`${summary(set)}\n`)
}
