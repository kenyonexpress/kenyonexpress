#!/usr/bin/env node
/**
 * Writes src/lib/admin/migration-manifest.ts from what is on disk.
 *
 * WHY A GENERATED MODULE AND NOT A readdir AT REQUEST TIME. The admin page that
 * renders this runs on Vercel, where only the files Next's tracer can see are
 * in the bundle. `migrations/` is data no import reaches, so a runtime
 * `readdirSync('migrations/pending')` works locally and returns ENOENT in
 * production -- the failure mode this repo has been bitten by often enough to
 * write it down. A generated module is imported, so it is traced, and it cannot
 * disagree with the directories because a test regenerates it and compares.
 *
 * Run: node scripts/build-migration-manifest.mjs
 * Gate: src/__tests__/pending-migrations-inventory.test.ts
 */
import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIRS = ['pending', 'applied', 'cancelled']
const OUT = 'src/lib/admin/migration-manifest.ts'

/**
 * NO SUMMARY FIELD, deliberately. The first draft carried each file's opening
 * comment line, and `hebrew-copy.test.ts` refused it: those lines are English
 * sentences and they were being rendered in the admin UI. The filename already
 * says what the migration is (`173_products_retired_commission_percent.sql`),
 * and the file itself is where the reasoning belongs. Weakening the Hebrew gate
 * to put developer prose on a screen would be the wrong trade.
 */

/**
 * The files git is tracking, or null when git cannot answer.
 *
 * TRACKED, NOT PRESENT ON DISK, and the difference is not academic: this repo
 * regularly has more than one agent working in it, and an uncommitted
 * `174_something.sql` sitting in `migrations/pending/` belongs to whoever is
 * still writing it. A manifest built from `readdir` would name their draft,
 * ship it to the admin screen, and turn its own gate red in every other working
 * copy. What deploys is what is committed, so that is what this describes.
 */
function trackedFiles(root) {
  try {
    const out = execFileSync('git', ['ls-files', '--', 'migrations'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    })
    const set = new Set(out.split('\n').filter(Boolean))
    // An empty answer means "not a git checkout" rather than "no migrations".
    return set.size > 0 ? set : null
  } catch {
    return null
  }
}

export function buildManifest(root = process.cwd()) {
  const tracked = trackedFiles(root)
  const entries = []
  for (const dir of DIRS) {
    const full = join(root, 'migrations', dir)
    const names = readdirSync(full)
      .filter((n) => n.endsWith('.sql'))
      .filter((n) => tracked === null || tracked.has(`migrations/${dir}/${n}`))
      .sort()
    const preflights = new Set(names.filter((n) => n.startsWith('preflight_')))
    for (const name of names) {
      if (name.startsWith('preflight_')) continue
      const number = name.match(/^(\d+[a-z]?)_/)?.[1] ?? ''
      entries.push({
        number,
        file: name,
        state: dir,
        hasPreflight: preflights.has(`preflight_${number}.sql`),
      })
    }
  }
  return entries.sort((a, b) => a.number.localeCompare(b.number, 'en', { numeric: true }))
}

export function renderModule(entries) {
  return `// GENERATED by scripts/build-migration-manifest.mjs. Do not edit by hand.
//
// Regenerate:  node scripts/build-migration-manifest.mjs
// Gated by:    src/__tests__/pending-migrations-inventory.test.ts, which rebuilds
//              this list from the directories and fails when the two differ.
//
// It describes THE REPOSITORY, not the database. A row saying \`pending\` means
// nobody has approved that file; it does not prove production lacks the change,
// and \`applied\` is this repo's record of an apply that was verified at the time.
// The database's own answer lives in supabase_migrations.schema_migrations.

export type MigrationState = 'pending' | 'applied' | 'cancelled'

export interface MigrationEntry {
  number: string
  file: string
  state: MigrationState
  /** Pending files must ship with preflight_<n>.sql beside them. */
  hasPreflight: boolean
}

export const MIGRATION_MANIFEST: readonly MigrationEntry[] = [
${entries.map(renderEntry).join('\n')}
] as const
`
}

/**
 * One entry, written the way biome would format it rather than the way
 * JSON.stringify does.
 *
 * The generator used to emit `JSON.stringify(entries, null, 2)`, which produces
 * double-quoted keys and no trailing comma. Biome rejects both, so every
 * regeneration left `pnpm lint` red until somebody ran `biome check --write`
 * by hand -- and the manual step is exactly what gets skipped. Emitting the
 * final shape directly means `pnpm migrations:manifest` leaves a tree that
 * lints clean.
 */
function renderEntry(entry) {
  return [
    '  {',
    `    number: '${entry.number}',`,
    `    file: '${entry.file}',`,
    `    state: '${entry.state}',`,
    `    hasPreflight: ${entry.hasPreflight},`,
    '  },',
  ].join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const entries = buildManifest()
  writeFileSync(OUT, renderModule(entries))
  console.log(`migration manifest: ${entries.length} files -> ${OUT}`)
}
