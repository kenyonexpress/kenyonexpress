/**
 * Cancellation, returns and refunds.
 *
 * THE NUMBERS ARE THE LAW'S, AND THE CODE ALREADY COMPUTES THEM.
 * `computeCancellationFee` in src/server/domain/orders/refund.ts is literally
 * `min(5% of the charge, ₪100)` and returns zero on a defect claim, and
 * `planOrderRefund` refuses outright to refund an order whose voucher is
 * `redeemed` or `expired`, waives the fee entirely on a same-clearing-day
 * cancellation, and waives it on a partial refund. Each of those four is a
 * sentence on this page, and none of them is a promise the system would break.
 *
 * THE ONE DISTINCTION THIS PAGE EXISTS TO MAKE is between a coupon before
 * redemption (a purchase that can be undone: money is with the platform and
 * the voucher is still `issued`) and after it (the business has already served
 * the customer, and the remainder was paid there, in cash the platform never
 * touched). A single "14 days" sentence covering both would promise a refund
 * the platform cannot execute.
 *
 * Set-date leisure services are the sharp edge: a restaurant, spa or cabin
 * booking falls under section 14ג(ד)(2), whose window closes 7 non-rest days
 * before the date, while a plain service falls under 14ג(ג) and closes 2. Both
 * are stated rather than averaged, and docs/legal/README.md lists the
 * classification as the open question for counsel.
 */
