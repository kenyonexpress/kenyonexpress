/**
 * The one animated slide, art-directed: still first everywhere, animation
 * swapped in on desktop once the page has loaded.
 *
 * `<picture>` rather than two rendered images, because that is the only shape
 * where the browser fetches ONE of them. Two `<Image>` elements toggled with
 * `hidden lg:block` both download - a `display:none` ancestor does not stop an
 * eager fetch - so the phone would have paid the 777KB anyway and then paid for
 * the still on top of it.
 *
 * The animated `<source>` is NOT in the initial markup. It used to be, plus a
 * head preload at high priority, and that pair made the animation the desktop
 * LCP at 12.1-12.9s on slow 4G + cpu/4: the hero's first paint waited for all
 * 794404 bytes while the optimized still - a ninth of the weight - sat unused
 * below the breakpoint. Now every viewport paints the still, and the desktop
 * fetches the animation at LOW priority after `window` load, mounting the
 * `<source>` only when the file has fully arrived, so the swap is a decode of
 * bytes already in cache and never a blank box.
 *
 * The swap cannot move LCP, and this is load-bearing: both files are 740x990
 * in the same `object-contain` box, so the swapped-in frame paints the exact
 * rect the still already painted, and LCP only accepts candidates LARGER than
 * the current champion - the same mechanics the autoplay gate below is built
 * on. [16]'s trade still stands: desktop gets the animation, it just starts a
 * beat later. `prefers-reduced-motion` keeps the still, which a markup-only
 * `<source>` could never offer.
 *
 * The `<img>` carries `loading="eager"` and `fetchPriority="high"` for the
 * priority slide because the still is now the homepage's real first hero paint
 * on every viewport.
 */
export function ArtDirectedHeroImage({
  animated,
  still,
  priority,
}: {
  animated: string
  still: string
  priority: boolean
}) {
  const [animationReady, setAnimationReady] = useState(false)

  useEffect(() => {
    // Media guards, not CSS: below the breakpoint the animation must never be
    // FETCHED, which no amount of hiding can express. Reduced motion keeps the
    // still for the same reason - the request itself is the cost.
    if (!window.matchMedia(HERO_ANIMATION_MEDIA).matches) return
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return

    let disposed = false
    // Two instances run this (one per breakpoint box); same URL, so the second
    // fetch is a cache hit and both swap together.
    const fetchAnimation = () => {
      if (disposed) return
      const probe = new window.Image()
      probe.fetchPriority = 'low'
      probe.onload = () => {
        if (!disposed) setAnimationReady(true)
      }
      probe.src = animated
    }
    if (document.readyState === 'complete') {
      fetchAnimation()
    } else {
      window.addEventListener('load', fetchAnimation, { once: true })
    }
    return () => {
      disposed = true
      window.removeEventListener('load', fetchAnimation)
    }
  }, [animated])

  const {
    props: { srcSet: stillSrcSet, ...rest },
  } = getImageProps({
    src: still,
    alt: '',
    fill: true,
    quality: 90,
    sizes: HERO_STILL_SIZES,
    className: HERO_IMAGE_CLASS,
  })

  return (
    <picture>
      {/*
        The animated file goes in RAW, not through getImageProps. Asking it for
        an `unoptimized` source returns `srcSet: undefined`, and a <source> with
        no srcset still MATCHES its media query - it just resolves to nothing.
        Measured on the first build of [16]: at 1440px the browser picked that
        empty source and the slide rendered a 1x1, so the desktop lost its
        animation while reporting no error at all. There is nothing for the
        optimizer to compute here anyway: an animated source is passed through
        byte-for-byte, so its only candidate is its own URL.
      */}
      {animationReady && (
        <source media={HERO_ANIMATION_MEDIA} srcSet={animated} type="image/webp" />
      )}
      <img
        {...rest}
        // Already in `rest`, restated because the slide image is decorative
        // and a lint rule cannot read an alt that arrives through a spread.
        alt=""
        srcSet={stillSrcSet}
        loading={priority ? 'eager' : 'lazy'}
        fetchPriority={priority ? 'high' : undefined}
        decoding="async"
      />
    </picture>
  )
}

function HeroSlideImage({ src, priority }: { src: string; priority: boolean }) {
  // next/image cannot resize an animated image without dropping the animation,
  // so it detects one and streams the original bytes through untouched. That is
  // why the hero slide is authored at exactly 2x its rendered size: the
  // optimizer will not do it for us. Marking animated sources unoptimized skips
  // a round trip that provably returns the file unchanged (verified: 47 frames
  // in, 47 frames and the same byte count out).
  //
  // This used to test only `.gif`, which silently stopped matching when the
  // 4.5MB GIF became an animated WebP.
  const isAnimated = /\.gif$/i.test(src) || ANIMATED_WEBP_SOURCES.has(src)
  const still = HERO_STILL_FRAMES[src]

  if (isAnimated && still) {
    return <ArtDirectedHeroImage animated={src} still={still} priority={priority} />
  }

  return (
    <SmartImage
      src={src}
      alt=""
      fill
      priority={priority}
      quality={95}
      sizes={HERO_IMAGE_SIZES}
      unoptimized={isAnimated}
      className={HERO_IMAGE_CLASS}
      fallbackClassName="absolute inset-0"
      iconSize={48}
    />
  )
}

function SlideImage({
  slide,
  priority,
}: {
  slide: HeroSlide
  priority: boolean
}) {
  const layout = slide.imageLayout ?? {
    offsetTop: ELECTRO_HERO.slider.image.offsetTop,
    widthPercent: ELECTRO_HERO.slider.image.widthPercent,
    minHeight: ELECTRO_HERO.slider.image.height,
  }

  return (
    <>
      {/*
        Two boxes, one per breakpoint. Never mark BOTH priority: a `hidden`
        ancestor does not cancel an eager fetch, so a phone was downloading the
        desktop raster (and a desktop the phone one) for the same slide. The
        visible box gets `priority`; the other stays lazy and typically does not
        fetch while `display:none`.
      */}
      <div
        className="absolute hidden overflow-hidden lg:block"
        style={{
          top: layout.offsetTop,
          insetInlineStart: `${layout.insetPercent ?? 0}%`,
          width: `${layout.widthPercent}%`,
          height: SLIDE.height - Math.max(0, layout.offsetTop),
        }}
      >
        <div className="relative h-full w-full" style={{ minHeight: layout.minHeight }}>
          {slide.image_url ? (
            <HeroSlideImage src={slide.image_url} priority={false} />
          ) : (
            <BrandPlaceholder
              className="absolute inset-0"
              markWidth={220}
              slot="תמונת הבאנר הראשי"
            />
          )}
        </div>
      </div>
      <div className="absolute end-0 bottom-0 h-[42%] w-full overflow-hidden lg:hidden">
        {slide.image_url ? (
          <HeroSlideImage src={slide.image_url} priority={priority} />
        ) : (
          <BrandPlaceholder className="absolute inset-0" markWidth={120} slot="תמונת הבאנר הראשי" />
        )}
      </div>
    </>
  )
}

